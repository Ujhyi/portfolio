type TranslationKey = Exclude<keyof typeof translations['sk'], 'categories'>;

interface LanguageContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey) => string;
  tCategory: (category: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    const stored = localStorage.getItem('spendlio_demo_lang') as Lang | null;
    if (stored) setLangState(stored);
  }, []);

  function setLang(next: Lang) {
    setLangState(next);
    localStorage.setItem('spendlio_demo_lang', next);
  }

  function t(key: TranslationKey): string {
    return translations[lang][key] ?? translations.sk[key] ?? key;
  }

  function tCategory(category: string): string {
    return (translations[lang].categories as Record<string, string>)[category] ?? category;
  }

  return <LanguageContext.Provider value={{ lang, setLang, t, tCategory }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage musí byť použité vnútri LanguageProvider');
  return ctx;
}